create table if not exists public.turnos (
  id bigint generated by default as identity primary key,
  numero_turno bigint not null,
  nombre_cafe text not null,
  estado text not null default 'pendiente',
  usuario_id uuid references auth.users (id) on delete set null,
  cliente_email text,
  created_at timestamptz not null default now()
);

alter table public.turnos
  add column if not exists usuario_id uuid references auth.users (id) on delete set null;

alter table public.turnos
  alter column estado set default 'pendiente';

update public.turnos
set estado = 'pendiente'
where estado is null;

alter table public.turnos
  alter column estado set not null;

create sequence if not exists public.turnos_numero_turno_seq;
alter sequence public.turnos_numero_turno_seq
  owned by public.turnos.numero_turno;
alter table public.turnos
  alter column numero_turno drop default;

select setval(
  'public.turnos_numero_turno_seq'::regclass,
  coalesce((select max(numero_turno) from public.turnos), 0) + 1,
  false
);

create or replace function public.asignar_numero_turno()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  new.numero_turno := nextval('public.turnos_numero_turno_seq'::regclass);
  return new;
end;
$$;

revoke all on function public.asignar_numero_turno() from public;

drop trigger if exists asignar_numero_turno_automatico on public.turnos;
create trigger asignar_numero_turno_automatico
  before insert on public.turnos
  for each row
  execute function public.asignar_numero_turno();

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'turnos_estado_check'
      and conrelid = 'public.turnos'::regclass
  ) then
    alter table public.turnos
      add constraint turnos_estado_check
      check (estado in ('pendiente', 'preparando', 'listo', 'entregado'));
  end if;
end;
$$;

create unique index if not exists turnos_numero_turno_key
  on public.turnos (numero_turno);

do $$
declare
  secuencia_id text;
begin
  secuencia_id := pg_get_serial_sequence('public.turnos', 'id');
  if secuencia_id is not null then
    execute format('revoke all on sequence %s from anon, authenticated', secuencia_id);
    execute format('grant usage, select on sequence %s to authenticated', secuencia_id);
  end if;
end;
$$;

update public.turnos as turno
set usuario_id = usuario.id
from auth.users as usuario
where turno.usuario_id is null
  and turno.cliente_email is not null
  and lower(turno.cliente_email) = lower(usuario.email);

alter table public.turnos enable row level security;

revoke all on table public.turnos from anon, authenticated;
grant select, insert, update on table public.turnos to authenticated;

drop policy if exists "Permitir lectura publica de turnos" on public.turnos;
drop policy if exists "Permitir insercion publica de turnos" on public.turnos;
drop policy if exists "Permitir actualizacion publica de turnos" on public.turnos;
drop policy if exists "Permitir eliminacion publica de turnos" on public.turnos;
drop policy if exists "Users can read own turnos" on public.turnos;
drop policy if exists "Admins can read all turnos" on public.turnos;
drop policy if exists "Users can create own turnos" on public.turnos;
drop policy if exists "Admins can update turnos" on public.turnos;

create policy "Users can read own turnos"
  on public.turnos
  for select
  to authenticated
  using ((select auth.uid()) = usuario_id);

create policy "Admins can read all turnos"
  on public.turnos
  for select
  to authenticated
  using (
    exists (
      select 1
      from public.profiles
      where profiles.id = (select auth.uid())
        and profiles.role = 'admin'
    )
  );

create policy "Users can create own turnos"
  on public.turnos
  for insert
  to authenticated
  with check (
    usuario_id = (select auth.uid())
    and cliente_email = (select auth.jwt() ->> 'email')
    and estado = 'pendiente'
  );

create policy "Admins can update turnos"
  on public.turnos
  for update
  to authenticated
  using (
    exists (
      select 1
      from public.profiles
      where profiles.id = (select auth.uid())
        and profiles.role = 'admin'
    )
  )
  with check (
    exists (
      select 1
      from public.profiles
      where profiles.id = (select auth.uid())
        and profiles.role = 'admin'
    )
  );

do $$
begin
  if not exists (
    select 1
    from pg_publication
    where pubname = 'supabase_realtime'
  ) then
    raise exception 'No existe la publicación supabase_realtime.';
  end if;

  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'turnos'
  ) then
    execute 'alter publication supabase_realtime add table public.turnos';
  end if;
end;
$$;
